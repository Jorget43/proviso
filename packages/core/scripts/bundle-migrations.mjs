// Turns the drizzle-kit output in ./drizzle into src/migrations.ts: the SQL as
// string constants, in the { journal, migrations } shape Drizzle's migrators
// take. Every platform imports it the same way (no bundler plugin for .sql
// files), and CI fails if it's out of date. Run via `npm run db:generate`.
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const journal = JSON.parse(readFileSync(path.join(root, 'drizzle/meta/_journal.json'), 'utf8'))
const entries = journal.entries.map(e => {
  const sql = readFileSync(path.join(root, 'drizzle', `${e.tag}.sql`), 'utf8').replace(/\r\n/g, '\n')
  return `    m${String(e.idx).padStart(4, '0')}: ${JSON.stringify(sql)},`
})
const out = `// GENERATED by scripts/bundle-migrations.mjs from ./drizzle — do not edit.
// Regenerate with \`npm run db:generate -w @proviso/core\`.

export const MIGRATIONS = {
  journal: ${JSON.stringify({ entries: journal.entries.map(({ idx, when, tag, breakpoints }) => ({ idx, when, tag, breakpoints })) })},
  migrations: {
${entries.join('\n')}
  } as Record<string, string>,
}
`
writeFileSync(path.join(root, 'src/migrations.ts'), out)
console.log(`src/migrations.ts: ${entries.length} migration(s)`)
